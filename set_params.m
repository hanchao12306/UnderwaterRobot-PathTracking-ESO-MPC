function params = set_params()
% ============================================================
%三维试验最优参数
% ---------- 制导律参数（式4-10、4-15） ----------
%params.kz   = 0.26;                    % 深度比例制导增益
%三组扰动参数
%1.params.M_nom = diag([200, 250, 250, 75]);   % 与真实 M 偏差约 5~7%
%  params.tau_d_func = @(t) [0.5*sin(0.1*t);
%                          0.3*cos(0.08*t);
%                          0.1*sin(0.12*t);
%                          0.2*cos(0.15*t)];
%2.params.M_nom = diag([183, 225, 225, 68]);
%  params.tau_d_func = @(t) [1.5*sin(0.1*t);
%                          0.9*cos(0.08*t);
%                          0.3*sin(0.12*t);
%                          0.6*cos(0.15*t)];
%3.params.M_nom = diag([161, 199, 199, 60]);
%  params.tau_d_func = @(t) [3.0*sin(0.1*t);
%                          1.8*cos(0.08*t);
%                          0.6*sin(0.12*t);
%                          1.2*cos(0.15*t)];
%
% 参数设置文件，对应论文第2章 2.3节、2.4节
% 说明：真实惯性矩阵 M 用于仿真，名义惯性矩阵 M_nom 用于控制器
% ============================================================

% ---------- 真实惯性矩阵 M 参数（式2-7、2-8） ----------
params.m11 = 215;  params.m22 = 265;
params.m33 = 265;  params.m44 = 80;
% 真实惯性矩阵 M = diag{m11, m22, m33, m44}（式2-7）
params.M = diag([params.m11, params.m22, params.m33, params.m44]);
params.Minv = inv(params.M);

% ---------- 名义惯性矩阵 M^i（式2-18，控制器只知道这个） ----------
params.M_nom = diag([200, 250, 250, 75]);
params.Minv_nom = inv(params.M_nom);

% ---------- 线性阻尼系数（式2-12） ----------
% 论文中 D_l = -diag(X_u, Y_v, Z_w, N_r)，X_u 为负
% 此处 d11 = -X_u > 0，表示正阻尼系数
params.d11 = 70;   params.d22 = 100;
params.d33 = 100;  params.d44 = 50;

% ---------- 阻尼矩阵 D(mu) = D_l + D_n(mu)（式2-11~2-13） ----------
% 线性项 + 非线性项（与|速度|成正比）
params.D_func = @(mu) diag([params.d11 + 5*abs(mu(1)), ...
                            params.d22 + 5*abs(mu(2)), ...
                            params.d33 + 5*abs(mu(3)), ...
                            params.d44 + 5*abs(mu(4))]);

% ---------- 科氏力与向心力矩阵 C(mu)（式2-9） ----------
% 满足斜对称性质 C(mu) = -C(mu)^T（性质2.2）
params.C_func = @(mu) [0, 0, 0, -params.m22*mu(2);
                       0, 0, 0,  params.m11*mu(1);
                       0, 0, 0, 0;
                       params.m22*mu(2), -params.m11*mu(1), 0, 0];

% ---------- 仿真参数 ----------
params.Ts = 0.1;           % 采样周期（式4-36 零阶保持离散化用）
params.T_total = 60;       % 总仿真时长

% ---------- 时变海流模型（论文4.7.2节海流扰动模型） ----------
params.current_func = @(t) [0.3 + 0.15*sin(0.05*t);
                            0.2 + 0.1*sin(0.04*t + pi/3);
                            0.05 + 0.03*sin(0.03*t)];

% ---------- 外部扰动力/力矩 tau_d（式2-6 中的 tau_d） ----------
params.tau_d_func = @(t) [0.5*sin(0.1*t);   % ← 修改这里
                          0.3*cos(0.08*t);
                          0.1*sin(0.12*t);
                          0.2*cos(0.15*t)];

% ---------- MPC参数（论文4.4节） ----------
params.Np = 15;                       % 预测时域 Np
params.Nc = 5;                        % 控制时域 Nc
% 原来是 diag([10,10,10,5])，降低角速度权重，允许一定的角速度误差
params.Q  = diag([10, 0.1, 10, 3.0]); 
% 原来是 0.01*eye(3)，大幅增加控制增量惩罚，强迫控制量平滑
params.R  = 0.4*eye(3);              % 控制增量权重 R（式4-45）
params.rho = 10;                      % 松弛因子权重（式4-45）

% ---------- ESO参数（式4-25 带宽参数化） ----------
params.omega_o = 3;                  % 观测器带宽 wo (rad/s)，取值范围5~20

% ---------- 制导律参数（式4-10、4-15） ----------
params.kz   = 0.25;                    % 深度比例制导增益
params.ke   = 2.0;                    % 自适应速度调节增益
params.umax = 1.5;                    % 最大纵荡速度
params.umin = 0.3;                    % 最小纵荡速度
params.wmax = 0.1;                    % 最大垂向速度

% ---------- CLF辅助控制律增益 Kc（式4-53） ----------
% 只对应可控通道 [u, w, r]
params.Kc = diag([1.5, 2.0, 1.3]);

% ---------- 控制约束（式4-47、4-48） ----------
% tau = [tau_u; tau_w; tau_r]（v通道无控制）
params.tau_min = [-200; -200; -100];
params.tau_max = [ 200;  200;  100];
params.du_min = [-50; -50; -20];
params.du_max = [ 50;  50;  20];


end